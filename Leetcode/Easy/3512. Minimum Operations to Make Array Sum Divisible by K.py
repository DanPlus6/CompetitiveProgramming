# Problem Name: 3512. Minimum Operations to Make Array Sum Divisible by K
# Problem Code: minimum-operations-to-make-array-sum-divisible-by-k
# Problem URL:  https://leetcode.com/problems/minimum-operations-to-make-array-sum-divisible-by-k/
class Solution:
    def minOperations(self, A: list[int], k: int) -> int: return sum(A)%k
        